"""Design-to-code: compile a KDL `system` into idiomatic tokens for a stack.

Shape: generate. Output is deterministic source text. Physics is converted
exactly: a KDL spring {response T (s), damping ζ} with unit mass has
stiffness k = (2π/T)² and damping coefficient c = 4πζ/T."""
from __future__ import annotations

import math
import re

from . import color

HEADER = "GENERATED by `kinetic export` from {src} — edit the KDL, then re-export."
STACKS = ("flutter", "swiftui", "compose", "react-native", "css")
SYSTEM_FONTS = re.compile(r"^(sf|san francisco|new york|system|roboto|-apple-system|system-ui)", re.I)


def _family(st, fams, size, platform="ios"):
    """A style's family: its own `family:` (a key of `families`, or a font name), else the
    display family at ≥ 28pt, the numeric family for tabular styles, the text family otherwise.
    A family may be per platform ({ios: …, android: …}); platform=None keeps the map."""
    own = st.get("family")
    if own is not None:
        fam = fams.get(own, own) if isinstance(own, str) else own
    else:
        key = "display" if size >= 28 else "numeric" if st.get("numerals") == "tabular" and "numeric" in fams else "text"
        fam = fams.get(key) or fams.get("text")
    if isinstance(fam, dict) and platform:
        fam = fam.get(platform) or fam.get("ios") or next(iter(fam.values()), None)
    return fam


# ------------------------------------------------------------------ utils
def ident(name: str, style: str = "camel") -> str:
    """Token name -> identifier valid in Dart/Swift/Kotlin/TS."""
    n = str(name)
    m = re.fullmatch(r"(\d+)x(\w+)", n)
    if m:
        n = "x" * int(m.group(1)) + m.group(2)
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", n) if p]
    if not parts:
        return "token"
    out = parts[0].lower() + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if out[0].isdigit():
        out = "t" + out
    if style == "pascal":
        out = out[:1].upper() + out[1:]
    return out


def spring_physics(response: float, damping: float, mass: float = 1.0) -> dict:
    w0 = 2 * math.pi / response
    return {"mass": mass, "stiffness": round(w0 * w0 * mass, 2),
            "damping": round(4 * math.pi * damping * mass / response, 2), "ratio": damping}


def spring_samples(response: float, damping: float, n: int = 40):
    """Simulate a unit step; return (duration_ms, [positions at n+1 even times])."""
    p = spring_physics(response, damping)
    k, c = p["stiffness"], p["damping"]
    x, v, t, dt = 0.0, 0.0, 0.0, 0.0005
    hist = [(0.0, 0.0)]
    while t < 5.0:
        a = -k * (x - 1) - c * v
        v += a * dt
        x += v * dt
        t += dt
        hist.append((t, x))
        if t > 0.05 and abs(1 - x) < 0.001 and abs(v) < 0.01:
            break
    total = hist[-1][0]
    out, j = [], 0
    for i in range(n + 1):
        target = total * i / n
        while j < len(hist) - 1 and hist[j][0] < target:
            j += 1
        out.append(round(hist[j][1], 4))
    out[-1] = 1.0
    return round(total * 1000), out


def _roles(doc):
    roles = (((doc.get("system") or {}).get("color") or {}).get("roles")) or {}
    light = roles.get("light") or {}
    dark = roles.get("dark") or light
    names = list(dict.fromkeys(list(light) + list(dark)))
    return names, light, dark


def _data(doc):
    """[(name, fill_light, on_light, fill_dark, on_dark)] from system.color.data."""
    out = []
    for name, v in ((((doc.get("system") or {}).get("color") or {}).get("data")) or {}).items():
        if isinstance(v, dict):
            fill = v.get("fill") or v.get("light")
            on = v.get("on") or v.get("on_light")
            fd, od = v.get("fill_dark") or v.get("dark") or fill, v.get("on_dark") or on
        else:
            fill, on, fd, od = v, None, v, None
        if not color.is_hex(str(fill)):
            continue
        on = on if color.is_hex(str(on)) else _on(_hex(fill))
        od = od if color.is_hex(str(od)) else _on(_hex(fd))
        out.append((str(name), _hex(fill), _hex(on), _hex(fd), _hex(od)))
    return out


def _sys(doc, *path, default=None):
    cur = doc.get("system") or {}
    for p in path:
        if not isinstance(cur, dict):
            return default
        cur = cur.get(p)
    return default if cur is None else cur


def _on(c: str) -> str:
    return "#FFFFFF" if color.wcag("#FFFFFF", c) >= color.wcag("#111111", c) else "#111111"


def _hex(v, fallback="#FF00FF") -> str:
    return color.to_hex(color.parse_hex(v)) if color.is_hex(str(v)) else fallback


def _weight(w) -> int:
    try:
        return max(100, min(900, int(round(float(w) / 100.0) * 100)))
    except (TypeError, ValueError):
        return 400


def _num(v, d=0.0) -> float:
    return float(v) if isinstance(v, (int, float)) else d


