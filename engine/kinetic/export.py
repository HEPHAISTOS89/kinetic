def to_css(doc, src="design.kdl") -> str:
    names, light, dark = _roles(doc)
    L = [f"/* {HEADER.format(src=src)} */", ":root {", "  color-scheme: light dark;"]
    for n in names:
        L.append(f"  --k-{n}: {_hex(light.get(n, dark.get(n)))};")
    for n, f, o, fd, od in _data(doc):
        L.append(f"  --k-data-{n}: {f};")
        L.append(f"  --k-data-{n}-on: {o};")
    for k, v in (_sys(doc, "space", "scale", default={}) or {}).items():
        L.append(f"  --k-space-{k}: {v}px;")
    for k, v in (_sys(doc, "shape", "radius", default={}) or {}).items():
        L.append(f"  --k-radius-{k}: {v}px;")
    mot = _sys(doc, "motion", default={}) or {}
    for k, v in (mot.get("durations") or {}).items():
        L.append(f"  --k-duration-{k}: {int(_num(v, 200))}ms;")
    for k, sp in (mot.get("springs") or {}).items():
        if isinstance(sp, dict):
            ms, pts = spring_samples(_num(sp.get("response"), 0.35), _num(sp.get("damping"), 0.9))
            L.append(f"  --k-spring-{k}: linear({', '.join(str(p) for p in pts)});")
            L.append(f"  --k-spring-{k}-duration: {ms}ms;")
    L.append("}\n")
    dark_block = "\n".join(f"    --k-{n}: {_hex(dark.get(n, light.get(n)))};" for n in names)
    L.append("@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n" + dark_block + "\n  }\n}")
    L.append(":root[data-theme=\"dark\"] {\n" + dark_block.replace("    ", "  ") + "\n}\n")
    fams = _sys(doc, "type", "families", default={}) or {}
    for name, st in (_sys(doc, "type", "scale", default={}) or {}).items():
        if not isinstance(st, dict):
            continue
        size = _num(st.get("size"), 16)
        fam = _family(st, fams, size, "web") or "system-ui"
        stack = "system-ui, -apple-system, sans-serif" if SYSTEM_FONTS.match(str(fam)) else f"'{fam}', system-ui, sans-serif"
        num = "\n  font-variant-numeric: tabular-nums;" if st.get("numerals") == "tabular" else ""
        if st.get("width") in ("condensed", "compressed", "expanded"):
            num += "\n  font-stretch: " + {"condensed": "75%", "compressed": "62.5%", "expanded": "125%"}[st["width"]] + ";"
        L.append(f".k-{name} {{\n  font-family: {stack};\n  font-size: {round(size / 16, 4)}rem;\n"
                 f"  line-height: {round(_num(st.get('line'), size * 1.3) / size, 4)};\n  font-weight: {_weight(st.get('weight'))};\n"
                 f"  letter-spacing: {_num(st.get('track'))}em;{num}\n}}")
    reduce = mot.get("reduce", "crossfade")
    L.append("\n@media (prefers-reduced-motion: reduce) {")
    L.append("  :root {")
    for k in (mot.get("springs") or {}):
        L.append(f"    --k-spring-{k}: ease-out;")
        L.append(f"    --k-spring-{k}-duration: {'0ms' if reduce == 'instant' else '150ms'};")
    L.append("  }")
    L.append("}")
    return "\n".join(L) + "\n"


def export(doc, stack: str, src="design.kdl", **kw) -> str:
    fn = {"flutter": to_flutter, "swiftui": to_swiftui, "compose": to_compose,
          "react-native": to_rn, "css": to_css, "web": to_css}.get(stack)
    if not fn:
        raise ValueError(f"unknown stack {stack!r}; use one of {', '.join(STACKS)}")
    return fn(doc, src, **kw) if kw else fn(doc, src)


