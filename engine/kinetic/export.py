COMPOSE_SLOT = {"display": "displaySmall", "title": "titleLarge", "headline": "headlineSmall", "body": "bodyLarge",
                "callout": "bodyMedium", "caption": "bodySmall", "label": "labelLarge", "micro": "labelSmall"}


def to_compose(doc, src="design.kdl", package="app.design") -> str:
    names, light, dark = _roles(doc)
    L = [f"// {HEADER.format(src=src)}", f"package {package}", "",
         "import androidx.compose.animation.core.Spring",
         "import androidx.compose.animation.core.SpringSpec",
         "import androidx.compose.animation.core.spring",
         "import androidx.compose.foundation.isSystemInDarkTheme",
         "import androidx.compose.foundation.shape.RoundedCornerShape",
         "import androidx.compose.material3.MaterialTheme",
         "import androidx.compose.material3.Typography",
         "import androidx.compose.material3.darkColorScheme",
         "import androidx.compose.material3.lightColorScheme",
         "import androidx.compose.runtime.Composable",
         "import androidx.compose.runtime.Immutable",
         "import androidx.compose.runtime.staticCompositionLocalOf",
         "import androidx.compose.runtime.CompositionLocalProvider",
         "import androidx.compose.ui.graphics.Color",
         "import androidx.compose.ui.text.TextStyle",
         "import androidx.compose.ui.text.font.FontWeight",
         "import androidx.compose.ui.unit.dp",
         "import androidx.compose.ui.unit.em",
         "import androidx.compose.ui.unit.sp", ""]
    L.append("@Immutable")
    L.append("data class KColors(" + ", ".join(f"val {ident(n)}: Color" for n in names) + ")\n")
    for tname, r in (("Light", light), ("Dark", dark)):
        L.append(f"val K{tname}Colors = KColors(" + ", ".join(
            f"{ident(n)} = Color(0xFF{_hex(r.get(n, light.get(n)))[1:]})" for n in names) + ")")
    L.append("\nval LocalKColors = staticCompositionLocalOf { KLightColors }\n")
    data = _data(doc)
    if data:
        L.append("/** Data colors (lines, categories): not roles, not accents. */")
        L.append("object KData {")
        for n, f, o, fd, od in data:
            L.append(f"    fun {ident(n)}(dark: Boolean) = if (dark) Color(0xFF{fd[1:]}) else Color(0xFF{f[1:]})")
            L.append(f"    fun {ident(n)}On(dark: Boolean) = if (dark) Color(0xFF{od[1:]}) else Color(0xFF{o[1:]})")
        L.append("}\n")

    def scheme(fn, r, var):
        args = [f"primary = {var}.{ident('accent')}", f"onPrimary = {var}.{ident('on-accent')}",
                f"surface = {var}.{ident('surface')}", f"onSurface = {var}.{ident('text')}"]
        if "bg" in names:
            args += [f"background = {var}.{ident('bg')}", f"onBackground = {var}.{ident('text')}"]
        if "text-2" in names:
            args.append(f"onSurfaceVariant = {var}.{ident('text-2')}")
        if "border" in names:
            args += [f"outline = {var}.{ident('border')}", f"outlineVariant = {var}.{ident('border')}"]
        if "danger" in names:
            args.append(f"error = {var}.{ident('danger')}")
        return f"private val K{fn}Scheme = {fn.lower()}ColorScheme(" + ", ".join(args) + ")"

    L.append(scheme("Light", light, "KLightColors"))
    L.append(scheme("Dark", dark, "KDarkColors"))
    L.append("\nobject KSpace {")
    for k, v in (_sys(doc, "space", "scale", default={}) or {}).items():
        L.append(f"    val {ident(k)} = {v}.dp")
    L.append("}\n")
    L.append("object KRadius {")
    for k, v in (_sys(doc, "shape", "radius", default={}) or {}).items():
        L.append(f"    val {ident(k)} = RoundedCornerShape({v}.dp)")
    L.append("}\n")
    L.append("object KType {")
    slots = []
    for name, st in (_sys(doc, "type", "scale", default={}) or {}).items():
        if not isinstance(st, dict):
            continue
        size = _num(st.get("size"), 16)
        line = _num(st.get("line"), size * 1.3)
        L.append(f"    val {ident(name)} = TextStyle(fontSize = {size}.sp, lineHeight = {line}.sp, "
                 f"fontWeight = FontWeight({_weight(st.get('weight'))}), letterSpacing = ({_num(st.get('track'))}).em)")
        if COMPOSE_SLOT.get(name):
            slots.append((COMPOSE_SLOT[name], ident(name)))
    L.append("}\n")
    L.append("val KTypography = Typography(" + ", ".join(f"{s} = KType.{i}" for s, i in slots) + ")\n")
    mot = _sys(doc, "motion", default={}) or {}
    L.append("object KMotion {")
    for k, v in (mot.get("durations") or {}).items():
        L.append(f"    const val {ident(k).upper()}_MS = {int(_num(v, 200))}")
    for k, sp in (mot.get("springs") or {}).items():
        if isinstance(sp, dict):
            p = spring_physics(_num(sp.get("response"), 0.35), _num(sp.get("damping"), 0.9))
            L.append(f"    fun <T> {ident(k)}(): SpringSpec<T> = spring(dampingRatio = {p['ratio']}f, stiffness = {p['stiffness']}f)")
    L.append(f"    // reduce-motion policy: {mot.get('reduce', 'crossfade')} — check ANIMATOR_DURATION_SCALE (knowledge/stacks/compose.md)")
    L.append("}\n")
    L.append("@Composable")
    L.append("fun KineticTheme(dark: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {")
    L.append("    CompositionLocalProvider(LocalKColors provides if (dark) KDarkColors else KLightColors) {")
    L.append("        MaterialTheme(colorScheme = if (dark) KDarkScheme else KLightScheme, typography = KTypography, content = content)")
    L.append("    }")
    L.append("}")
    return "\n".join(L) + "\n"


# ----------------------------------------------------------- react native
def to_rn(doc, src="design.kdl") -> str:
    names, light, dark = _roles(doc)
    L = [f"// {HEADER.format(src=src)}", "import { Platform, useColorScheme, type TextStyle } from 'react-native';", ""]
    for tname, r in (("light", light), ("dark", dark)):
        L.append(f"const {tname} = {{")
        for n in names:
            L.append(f"  {ident(n)}: '{_hex(r.get(n, light.get(n)))}',")
        L.append("} as const;\n")
    L.append("export const palette = { light, dark } as const;\n")
    data = _data(doc)
    if data:
        L.append("/** Data colors (lines, categories): not roles, not accents. */")
        L.append("export const dataColors = {")
        for n, f, o, fd, od in data:
            L.append(f"  {ident(n)}: {{ light: {{ fill: '{f}', on: '{o}' }}, dark: {{ fill: '{fd}', on: '{od}' }} }},")
        L.append("} as const;\n")
        for tname, dk in (("dataLight", False), ("dataDark", True)):
            L.append(f"const {tname} = {{")
            for n, f, o, fd, od in data:
                L.append(f"  {ident(n)}: {{ fill: '{fd if dk else f}', on: '{od if dk else o}' }},")
            L.append("} as const;\n")
    L.append("export const space = {")
    for k, v in (_sys(doc, "space", "scale", default={}) or {}).items():
        L.append(f"  {ident(k)}: {v},")
    L.append("} as const;\n")
    L.append("export const radius = {")
    for k, v in (_sys(doc, "shape", "radius", default={}) or {}).items():
        L.append(f"  {ident(k)}: {v},")
    L.append("} as const;\n")
    L.append("export const type = {")
    fams = _sys(doc, "type", "families", default={}) or {}
    for name, st in (_sys(doc, "type", "scale", default={}) or {}).items():
        if not isinstance(st, dict):
            continue
        size = _num(st.get("size"), 16)
        fam = _family(st, fams, size, None)
        if isinstance(fam, dict):
            per = {k: v for k, v in fam.items() if k in ("ios", "android") and not SYSTEM_FONTS.match(str(v))}
            fam_s = (", fontFamily: Platform.select({ " + ", ".join(f"{k}: '{v}'" for k, v in per.items()) + " })") if per else ""
        else:
            fam_s = f", fontFamily: '{fam}'" if fam and not SYSTEM_FONTS.match(str(fam)) else ""
        num = ", fontVariant: ['tabular-nums']" if st.get("numerals") == "tabular" else ""
        L.append(f"  {ident(name)}: {{ fontSize: {size}, lineHeight: {_num(st.get('line'), size * 1.3)}, "
                 f"fontWeight: '{_weight(st.get('weight'))}', letterSpacing: {round(_num(st.get('track')) * size, 3)}{fam_s}{num} }},")
    L.append("} satisfies Record<string, TextStyle>;\n")
    mot = _sys(doc, "motion", default={}) or {}
    L.append("/** Reanimated withSpring configs (physics form; mass 1). */")
    L.append("export const springs = {")
    for k, sp in (mot.get("springs") or {}).items():
        if isinstance(sp, dict):
            p = spring_physics(_num(sp.get("response"), 0.35), _num(sp.get("damping"), 0.9))
            L.append(f"  {ident(k)}: {{ mass: 1, stiffness: {p['stiffness']}, damping: {p['damping']} }},")
    L.append("} as const;\n")
    L.append("export const durations = {")
    for k, v in (mot.get("durations") or {}).items():
        L.append(f"  {ident(k)}: {int(_num(v, 200))},")
    L.append("} as const;\n")
    L.append(f"/** Reduce-motion policy: {mot.get('reduce', 'crossfade')} (pair with Reanimated useReducedMotion()). */")
    L.append(f"export const reduceMotion = '{mot.get('reduce', 'crossfade')}' as const;\n")
    L.append("export function useTokens() {")
    L.append("  const scheme = useColorScheme();")
    data_s = ", data: scheme === 'dark' ? dataDark : dataLight" if data else ""
    L.append(f"  return {{ color: scheme === 'dark' ? dark : light{data_s}, space, radius, type, springs, durations }};")
    L.append("}")
    return "\n".join(L) + "\n"


