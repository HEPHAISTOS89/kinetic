def to_swiftui(doc, src="design.kdl") -> str:
    names, light, dark = _roles(doc)
    L = [f"// {HEADER.format(src=src)}", "import SwiftUI", "#if canImport(UIKit)", "import UIKit", "#elseif canImport(AppKit)", "import AppKit", "#endif", ""]
    L.append("extension Color {")
    for n in names:
        lh, dh = _hex(light.get(n, dark.get(n))), _hex(dark.get(n, light.get(n)))
        L.append(f"    static let k{ident(n, 'pascal')} = Color(kLight: 0x{lh[1:]}, kDark: 0x{dh[1:]})")
    for n, f, o, fd, od in _data(doc):
        L.append(f"    /// data color `{n}` (not a role, not an accent)")
        L.append(f"    static let kData{ident(n, 'pascal')} = Color(kLight: 0x{f[1:]}, kDark: 0x{fd[1:]})")
        L.append(f"    static let kData{ident(n, 'pascal')}On = Color(kLight: 0x{o[1:]}, kDark: 0x{od[1:]})")
    L.append("")
    L.append("    init(kLight: UInt32, kDark: UInt32) {")
    L.append("        #if canImport(UIKit)")
    L.append("        self.init(uiColor: UIColor { $0.userInterfaceStyle == .dark ? UIColor(kRGB: kDark) : UIColor(kRGB: kLight) })")
    L.append("        #elseif canImport(AppKit)")
    L.append("        self.init(nsColor: NSColor(name: nil) { $0.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? NSColor(kRGB: kDark) : NSColor(kRGB: kLight) })")
    L.append("        #else")
    L.append("        self.init(red: Double((kLight >> 16) & 0xFF) / 255, green: Double((kLight >> 8) & 0xFF) / 255, blue: Double(kLight & 0xFF) / 255)")
    L.append("        #endif")
    L.append("    }")
    L.append("}\n")
    L.append("extension ShapeStyle where Self == Color {")
    for n in names:
        L.append(f"    static var k{ident(n, 'pascal')}: Color {{ Color.k{ident(n, 'pascal')} }}")
    L.append("}\n")
    L.append("#if canImport(UIKit)")
    L.append("private extension UIColor {")
    L.append("    convenience init(kRGB: UInt32) {")
    L.append("        self.init(red: CGFloat((kRGB >> 16) & 0xFF) / 255, green: CGFloat((kRGB >> 8) & 0xFF) / 255,")
    L.append("                  blue: CGFloat(kRGB & 0xFF) / 255, alpha: 1)")
    L.append("    }")
    L.append("}")
    L.append("#elseif canImport(AppKit)")
    L.append("private extension NSColor {")
    L.append("    convenience init(kRGB: UInt32) {")
    L.append("        self.init(srgbRed: CGFloat((kRGB >> 16) & 0xFF) / 255, green: CGFloat((kRGB >> 8) & 0xFF) / 255,")
    L.append("                  blue: CGFloat(kRGB & 0xFF) / 255, alpha: 1)")
    L.append("    }")
    L.append("}")
    L.append("#endif\n")
    L.append("enum KSpace {")
    for k, v in (_sys(doc, "space", "scale", default={}) or {}).items():
        L.append(f"    static let {ident(k)}: CGFloat = {float(v)}")
    for k, v in (_sys(doc, "space", "margins", default={}) or {}).items():
        L.append(f"    static let margin{ident(k, 'pascal')}: CGFloat = {float(v)}")
    L.append("}\n")
    corner = ".continuous" if _sys(doc, "shape", "corner", default="continuous") == "continuous" else ".circular"
    L.append("enum KRadius {")
    for k, v in (_sys(doc, "shape", "radius", default={}) or {}).items():
        L.append(f"    static let {ident(k)}: CGFloat = {float(v)}")
    L.append(f"    static func shape(_ radius: CGFloat) -> RoundedRectangle {{ RoundedRectangle(cornerRadius: radius, style: {corner}) }}")
    L.append("}\n")
    L.append("struct KTextStyle {")
    L.append("    let size: CGFloat, line: CGFloat, weight: Font.Weight, tracking: CGFloat")
    L.append("    let relativeTo: Font.TextStyle, design: Font.Design, family: String?, tabular: Bool")
    L.append("    var width: Font.Width = .standard")
    L.append("}\n")
    fams = _sys(doc, "type", "families", default={}) or {}
    L.append("enum KType {")
    wmap = {100: "ultraLight", 200: "thin", 300: "light", 400: "regular", 500: "medium", 600: "semibold",
            700: "bold", 800: "heavy", 900: "black"}
    for name, st in (_sys(doc, "type", "scale", default={}) or {}).items():
        if not isinstance(st, dict):
            continue
        size = _num(st.get("size"), 17)
        line = _num(st.get("line"), size * 1.3)
        fam = _family(st, fams, size, "ios")
        design, custom = _swift_design(fam)
        fam_s = f'"{custom}"' if custom else "nil"
        width = str(st.get("width") or ("condensed" if "condensed" in str(fam).lower() else
                                         "compressed" if "compressed" in str(fam).lower() else
                                         "expanded" if "expanded" in str(fam).lower() else "standard"))
        if width not in ("standard", "condensed", "compressed", "expanded"):
            width = "standard"
        L.append(f"    static let {ident(name)} = KTextStyle(size: {size}, line: {line}, weight: .{wmap[_weight(st.get('weight'))]}, "
                 f"tracking: {_num(st.get('track'))}, relativeTo: .{_relative(size, str(name))}, design: .{design}, family: {fam_s}, "
                 f"tabular: {'true' if st.get('numerals') == 'tabular' else 'false'}, width: .{width})")
    L.append("}\n")
    L.append("/// Applies a KDL type style with Dynamic Type scaling, em-based tracking and line height.")
    L.append("struct KTextModifier: ViewModifier {")
    L.append("    let style: KTextStyle")
    L.append("    @ScaledMetric private var size: CGFloat")
    L.append("    init(_ style: KTextStyle) {")
    L.append("        self.style = style")
    L.append("        _size = ScaledMetric(wrappedValue: style.size, relativeTo: style.relativeTo)")
    L.append("    }")
    L.append("    private var font: Font {")
    L.append("        let base: Font = style.family.map { Font.custom($0, size: size).weight(style.weight) }")
    L.append("            ?? .system(size: size, weight: style.weight, design: style.design).width(style.width)")
    L.append("        return style.tabular ? base.monospacedDigit() : base")
    L.append("    }")
    L.append("    func body(content: Content) -> some View {")
    L.append("        let scale = size / style.size")
    L.append("        // SF's natural line height is ~1.2em; lineSpacing adds the remainder of the KDL line height.")
    L.append("        content.font(font)")
    L.append("            .tracking(style.tracking * size)")
    L.append("            .lineSpacing(max(0, (style.line - style.size * 1.2) * scale))")
    L.append("    }")
    L.append("}\n")
    L.append("extension View {")
    L.append("    func kText(_ style: KTextStyle) -> some View { modifier(KTextModifier(style)) }")
    L.append("}\n")
    mot = _sys(doc, "motion", default={}) or {}
    reduce = mot.get("reduce", "crossfade")
    L.append("extension Animation {")
    for k, sp in (mot.get("springs") or {}).items():
        if isinstance(sp, dict):
            L.append(f"    static let k{ident(k, 'pascal')} = Animation.spring(response: {_num(sp.get('response'), 0.35)}, "
                     f"dampingFraction: {_num(sp.get('damping'), 0.9)})")
    for k, v in (mot.get("durations") or {}).items():
        L.append(f"    static let k{ident(k, 'pascal')} = Animation.easeOut(duration: {round(_num(v, 200) / 1000, 3)})")
    L.append("}\n")
    L.append(f"/// Reduce-motion policy: {reduce}.")
    L.append("struct KAnimated<V: Equatable>: ViewModifier {")
    L.append("    @Environment(\\.accessibilityReduceMotion) private var reduceMotion")
    L.append("    let animation: Animation")
    L.append("    let value: V")
    L.append("    func body(content: Content) -> some View {")
    alt = "nil" if reduce == "instant" else ".easeInOut(duration: 0.15)"
    L.append(f"        content.animation(reduceMotion ? {alt} : animation, value: value)")
    L.append("    }")
    L.append("}\n")
    L.append("extension View {")
    L.append("    func kAnimation<V: Equatable>(_ animation: Animation, value: V) -> some View {")
    L.append("        modifier(KAnimated(animation: animation, value: value))")
    L.append("    }")
    L.append("}\n")
    hap = _sys(doc, "haptics", default={}) or {}
    if hap:
        L.append("@available(iOS 17.0, macOS 14.0, *)")
        L.append("enum KHaptic {")
        for k, v in hap.items():
            L.append(f"    static let {ident(k)}: SensoryFeedback = {SWIFT_HAPTIC.get(str(v), '.selection')}")
        L.append("}")
    return "\n".join(L) + "\n"


