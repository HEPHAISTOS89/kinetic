def to_flutter(doc, src="design.kdl") -> str:
    names, light, dark = _roles(doc)
    fields = [(n, ident(n)) for n in names]
    L = []
    L.append(f"// {HEADER.format(src=src)}")
    L.append("// ignore_for_file: public_member_api_docs")
    L.append("import 'package:flutter/material.dart';")
    L.append("import 'package:flutter/services.dart';\n")
    L.append("@immutable")
    L.append("class KColors extends ThemeExtension<KColors> {")
    L.append("  const KColors({" + ", ".join(f"required this.{i}" for _, i in fields) + "});")
    for _, i in fields:
        L.append(f"  final Color {i};")

    def inst(r):
        return "KColors(" + ", ".join(
            f"{i}: Color(0xFF{_hex(r.get(n, light.get(n)))[1:]})" for n, i in fields) + ")"

    L.append(f"\n  static const light = {inst(light)};")
    L.append(f"  static const dark = {inst(dark)};\n")
    L.append("  static KColors of(BuildContext context) => Theme.of(context).extension<KColors>()!;\n")
    L.append("  @override")
    L.append("  KColors copyWith({" + ", ".join(f"Color? {i}" for _, i in fields) + "}) =>")
    L.append("      KColors(" + ", ".join(f"{i}: {i} ?? this.{i}" for _, i in fields) + ");\n")
    L.append("  @override")
    L.append("  KColors lerp(ThemeExtension<KColors>? other, double t) {")
    L.append("    if (other is! KColors) return this;")
    L.append("    return KColors(" + ", ".join(f"{i}: Color.lerp({i}, other.{i}, t)!" for _, i in fields) + ");")
    L.append("  }\n}\n")
    data = _data(doc)
    if data:
        L.append("/// Data colors (lines, categories): not roles, not accents. `on` = label color on the fill.")
        L.append("abstract final class KData {")
        for n, f, o, fd, od in data:
            L.append(f"  static Color {ident(n)}(Brightness b) => b == Brightness.dark ? const Color(0xFF{fd[1:]}) : const Color(0xFF{f[1:]});")
            L.append(f"  static Color {ident(n)}On(Brightness b) => b == Brightness.dark ? const Color(0xFF{od[1:]}) : const Color(0xFF{o[1:]});")
        L.append("}\n")
    space = _sys(doc, "space", "scale", default={}) or {}
    L.append("abstract final class KSpace {")
    for k, v in space.items():
        L.append(f"  static const double {ident(k)} = {float(v)};")
    for k, v in (_sys(doc, "space", "margins", default={}) or {}).items():
        L.append(f"  static const double margin{ident(k, 'pascal')} = {float(v)};")
    L.append("}\n")
    L.append("abstract final class KRadius {")
    for k, v in (_sys(doc, "shape", "radius", default={}) or {}).items():
        L.append(f"  static const double {ident(k)} = {float(v)};")
    L.append("}\n")
    fams = _sys(doc, "type", "families", default={}) or {}
    scale = _sys(doc, "type", "scale", default={}) or {}
    L.append("abstract final class KType {")
    for name, st in scale.items():
        if not isinstance(st, dict):
            continue
        size = _num(st.get("size"), 16)
        line = _num(st.get("line"), size * 1.3)
        fam = _family(st, fams, size, "android")
        fam_arg = f", fontFamily: '{fam}'" if fam and not SYSTEM_FONTS.match(str(fam)) else ""
        feats = ", fontFeatures: [FontFeature.tabularFigures()]" if st.get("numerals") == "tabular" else ""
        wdth = {"condensed": 75, "compressed": 62.5, "expanded": 125}.get(str(st.get("width")))
        if wdth:  # variable fonts honour it; a static condensed cut is named by `family`
            feats += f", fontVariations: [FontVariation('wdth', {float(wdth)})]"
        L.append(f"  static const TextStyle {ident(name)} = TextStyle(fontSize: {size}, height: {round(line / size, 4)}, "
                 f"fontWeight: FontWeight.w{_weight(st.get('weight'))}, letterSpacing: {round(_num(st.get('track')) * size, 3)}"
                 f"{fam_arg}{feats});")
    L.append("}\n")
    mot = _sys(doc, "motion", default={}) or {}
    L.append("abstract final class KMotion {")
    for k, v in (mot.get("durations") or {}).items():
        L.append(f"  static const Duration {ident(k)} = Duration(milliseconds: {int(_num(v, 200))});")
    for k, sp in (mot.get("springs") or {}).items():
        if isinstance(sp, dict):
            p = spring_physics(_num(sp.get("response"), 0.35), _num(sp.get("damping"), 0.9))
            L.append(f"  /// response {sp.get('response')}s, damping ratio {sp.get('damping')}")
            L.append(f"  static final SpringDescription {ident(k)} = SpringDescription.withDampingRatio("
                     f"mass: 1, stiffness: {p['stiffness']}, ratio: {p['ratio']});")
    reduce = mot.get("reduce", "crossfade")
    L.append(f"\n  /// Reduce-motion policy: {reduce}. Use for every Duration you animate with.")
    L.append("  static Duration of(BuildContext context, Duration d) =>")
    L.append("      MediaQuery.disableAnimationsOf(context) ? " +
             ("Duration.zero" if reduce == "instant" else "const Duration(milliseconds: 150)") + " : d;")
    L.append("  static bool reduced(BuildContext context) => MediaQuery.disableAnimationsOf(context);")
    L.append("}\n")
    hap = _sys(doc, "haptics", default={}) or {}
    if hap:
        L.append("abstract final class KHaptics {")
        for k, v in hap.items():
            L.append(f"  static Future<void> {ident(k)}() => {FLUTTER_HAPTIC.get(str(v), 'HapticFeedback.selectionClick()')};")
        L.append("}\n")
    danger = light.get("danger", "#B3261E")
    ddanger = dark.get("danger", danger)
    slots = []
    for name, st in scale.items():
        slot = TEXT_THEME_SLOT.get(name)
        if slot and slot not in [s for s, _ in slots]:
            slots.append((slot, ident(name)))
    L.append("ThemeData kineticTheme(Brightness brightness) {")
    L.append("  final c = brightness == Brightness.dark ? KColors.dark : KColors.light;")
    L.append("  final dark = brightness == Brightness.dark;")
    L.append("  final scheme = ColorScheme(")
    L.append("    brightness: brightness,")
    a, oa, s, t = (ident(x) for x in ("accent", "on-accent", "surface", "text"))
    L.append(f"    primary: c.{a}, onPrimary: c.{oa}, secondary: c.{a}, onSecondary: c.{oa},")
    L.append(f"    error: dark ? const Color(0xFF{_hex(ddanger)[1:]}) : const Color(0xFF{_hex(danger)[1:]}),")
    L.append(f"    onError: dark ? const Color(0xFF{_on(_hex(ddanger))[1:]}) : const Color(0xFF{_on(_hex(danger))[1:]}),")
    L.append(f"    surface: c.{s}, onSurface: c.{t},")
    if "text-2" in names:
        L.append(f"    onSurfaceVariant: c.{ident('text-2')},")
    if "border" in names:
        L.append(f"    outline: c.{ident('border')}, outlineVariant: c.{ident('border')},")
    L.append("  );")
    L.append("  return ThemeData(")
    L.append("    useMaterial3: true,")
    L.append("    brightness: brightness,")
    L.append("    colorScheme: scheme,")
    if "bg" in names:
        L.append(f"    scaffoldBackgroundColor: c.{ident('bg')},")
    if slots:
        L.append("    textTheme: TextTheme(" + ", ".join(f"{slot}: KType.{i}" for slot, i in slots) +
                 f").apply(bodyColor: c.{t}, displayColor: c.{t}),")
    L.append("    extensions: <ThemeExtension<dynamic>>[c],")
    L.append("  );")
    L.append("}")
    return "\n".join(L) + "\n"


